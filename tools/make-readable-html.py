"""Render the project's key documents as standalone HTML you can just open.

Owner direction, 2026-09-29, verbatim: *"make this html open able ... as if i open this with
edge to read it its all fucked up"* and *"its a massive text wall needs style formating and
beautiful layout"*.

An XSLT stylesheet was tried first and **was the wrong answer**: Chromium blocks XSLT loaded
from a `file://` URL, so Edge showed a blank page instead of raw XML -- worse than the
problem. Standalone HTML with the styling inlined has no such restriction and opens from
anywhere.

Output goes to `outputs/readable/`, beside the mod register, and is regenerated rather than
edited. Nothing here ships in the mod package.

Usage
-----
    python tools/make-readable-html.py
"""

import glob
import io
import os
import re
import sys
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "outputs", "readable")
ABOUT = os.path.join(REPO, "Mod", "Rimrooms - Async Industries", "About", "About.xml")

