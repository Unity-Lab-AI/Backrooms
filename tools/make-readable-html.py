def esc(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def page(title, body):
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            "<title>%s</title><style>%s</style></head><body><main>%s"
            "<p class=\"note\">Generated by <code>tools/make-readable-html.py</code>. "
            "Regenerate rather than edit; nothing here ships in the mod package.</p>"
            "</main></body></html>\n" % (esc(title), STYLE, body))


def inline(text):
    """The small amount of markdown that actually appears in these documents."""
    text = esc(text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    return text


def render_about():
    root = ET.parse(ABOUT).getroot()

    def value(tag):
        node = root.find(tag)
        return (node.text or "").strip() if node is not None else ""

    versions = "".join('<span class="pill">%s</span>' % esc((li.text or "").strip())
                       for li in root.findall("supportedVersions/li"))
    body = ['<h1>%s</h1>' % esc(value("name")),
            '<p class="sub">by %s</p>' % esc(value("author")),
            '<dl class="meta">',
            '<dt>Version</dt><dd>%s</dd>' % esc(value("modVersion")),
            '<dt>Package</dt><dd><code>%s</code></dd>' % esc(value("packageId")),
            '<dt>Supports</dt><dd>%s</dd>' % versions,
            '</dl>']

    for block in re.split(r"\n\s*\n", value("description")):
        block = " ".join(block.split())
        if not block:
            continue
        if block.startswith("---"):
            body.append("<h2>%s</h2>" % esc(block.strip("- ").strip()))
        elif block.startswith("Development build"):
            body.append('<p class="lede">%s</p>' % esc(block))
        else:
            body.append("<p>%s</p>" % esc(block))
    return page(value("name"), "".join(body))


def render_markdown(path, title):
    lines = io.open(path, encoding="utf-8-sig").read().split("\n")
    body, in_code, in_table = [], False, False

    def close_table():
        if in_table:
            body.append("</table>")

    for line in lines:
        stripped = line.rstrip()
        if stripped.startswith("```"):
            if in_code:
                body.append("</code></pre>")
            else:
                close_table()
                in_table = False
                body.append("<pre><code>")
            in_code = not in_code
            continue
        if in_code:
            body.append(esc(line) + "\n")
            continue

        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if all(set(c) <= set("-: ") and c for c in cells):
                continue
            if not in_table:
                body.append("<table>")
                in_table = True
                body.append("<tr>%s</tr>" % "".join("<th>%s</th>" % inline(c) for c in cells))
                continue
            body.append("<tr>%s</tr>" % "".join("<td>%s</td>" % inline(c) for c in cells))
            continue
        close_table()
        in_table = False

        if not stripped.strip():
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if heading:
            level = min(len(heading.group(1)), 3)
            tag = "h1" if level == 1 else ("h2" if level == 2 else "h3")
            body.append("<%s>%s</%s>" % (tag, inline(heading.group(2)), tag))
            continue
        bullet = re.match(r"^\s*[-*]\s+(.*)$", stripped)
        if bullet:
            if not body or not body[-1].startswith("<ul>"):
                body.append("<ul>")
            body.append("<li>%s</li>" % inline(bullet.group(1)))
            continue
        if body and body[-1].startswith("<li>"):
            body.append("</ul>")
        body.append("<p>%s</p>" % inline(stripped))

    close_table()
    return page(title, "".join(body))


def main():
    if not os.path.isdir(OUT):
        os.makedirs(OUT)

    written = []

    io.open(os.path.join(OUT, "About.html"), "w", encoding="utf-8", newline="").write(render_about())
    written.append(("About.html", "The mod's own description, as a player sees it"))

    docs = [
        ("README.md", "README.html", "Project overview"),
        ("CHANGELOG.md", "CHANGELOG.html", "Every released change"),
        (os.path.join("docs", "NOW.md"), "NOW.html", "What is true right now"),
        (os.path.join("docs", "TODO.md"), "TODO.html", "The working queue"),
        (os.path.join("docs", "ROADMAP.md"), "ROADMAP.html", "Phases and milestones"),
    ]
    for source, target, label in docs:
        full = os.path.join(REPO, source)
        if not os.path.isfile(full):
            continue
        title = os.path.basename(source)
        io.open(os.path.join(OUT, target), "w", encoding="utf-8", newline="").write(
            render_markdown(full, title))
        written.append((target, label))

    index = ['<h1>Rimrooms &mdash; readable</h1>',
             '<p class="sub">Open any of these in a browser.</p>',
             '<ul class="index">']
    for name, label in written:
        index.append('<li><a href="%s">%s</a> &mdash; %s</li>' % (name, name, esc(label)))
    index.append("</ul>")
    io.open(os.path.join(OUT, "index.html"), "w", encoding="utf-8", newline="").write(
        page("Rimrooms - readable", "".join(index)))

    print("written to outputs/readable/")
    for name, _ in [("index.html", "")] + written:
        print("  %s" % name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
